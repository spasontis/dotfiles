#!/bin/sh
# Смена раскладки уже набранного текста в строке ввода Claude Code
# (prefix Tab). «ghbdtn» становится «привет» и обратно.
#
# Направление определяет switch-layout.pl по самому тексту, здесь только
# чтение с экрана и замена: строка ввода стирается Backspace во всю ширину
# панели и набирается заново. Точная длина не нужна — Backspace в пустом
# вводе ничего не делает, а в одну экранную строку больше ширины панели
# символов не влезет.
#
# Отдельной отмены нет и не нужно: повторное нажатие переводит обратно,
# таблица двусторонняя и знаки препинания в ней тоже (проверено круговым
# прогоном 23.09.2026).
#
# ВНИМАНИЕ: работает только с вводом в ОДНУ экранную строку. Перенесённый
# ввод с экрана не восстановить: перенос по границе слова съедает пробел, а
# перенос посреди длинного слова не съедает ничего, и на экране эти два
# случая выглядят одинаково — как и набранный вручную перевод строки. Вернуть
# не тот текст здесь хуже, чем не сделать ничего, поэтому такой ввод скрипт
# не трогает и говорит об этом.
set -eu

pane="${1:?нужен pane_id}"
here=$(dirname "$0")

box=$("$here/claude-input-box.sh" "$pane")
head=$(printf '%s\n' "$box" | sed -n 1p)

case "$head" in
"НЕТ РАМКИ") tmux display-message -t "$pane" "строка ввода Claude Code на экране не найдена"; exit 0 ;;
"НЕ ОПОЗНАНА") tmux display-message -t "$pane" "рамка найдена, маркер строки ввода не опознан"; exit 0 ;;
"ПУСТО") exit 0 ;;
esac

if [ "${head% *}" != "${head#* }" ]; then
	tmux display-message -t "$pane" "ввод занимает несколько строк, раскладку не меняю"
	exit 0
fi

# Маркер и неразрывный пробел — первые пять байт строки.
text=$(printf '%s\n' "$box" | sed -n 2p | cut -b 6-)
new=$(printf '%s' "$text" | "$here/switch-layout.pl") || exit 0
[ -n "$new" ] || exit 0

width=$(tmux display-message -p -t "$pane" '#{pane_width}')
tmux send-keys -t "$pane" -N "$width" BSpace
tmux send-keys -t "$pane" -l -- "$new"
