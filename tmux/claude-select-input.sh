#!/bin/sh
# Выделение текста строки ввода Claude Code (prefix a).
#
# Мышью строку ввода Claude не выделить набело: слева от текста стоит маркер
# «❯» с неразрывным пробелом, сверху и снизу — линейки рамки, а справа панель
# добита пробелами. Скрипт находит рамку на экране панели, заводит copy-mode
# и ставит выделение ровно по тексту: от первого символа после маркера до
# последнего непробельного символа последней строки ввода.
#
# Копирование остаётся за человеком: выделение живое, дальше y (copy-pipe в
# буфер ОС, см. .tmux.conf) или Escape. Так же ведёт себя выделение мышью.
#
# Разметка строки ввода, снята с работающей панели 23.09.2026 на 2.1.280:
#
#   ─────────────────────────────  линейка во всю ширину панели
#   ❯<U+00A0>текст                 маркер, НЕРАЗРЫВНЫЙ пробел, текст
#   ─────────────────────────────  линейка
#
# Маркер «❯» встречается и выше по экрану — им же помечены уже отправленные
# сообщения в расшифровке. Поэтому опознаём не по маркеру, а по паре линеек:
# берём нижнюю линейку на экране и ближайшую линейку над ней, между ними и
# лежит ввод, сколько бы строк он ни занимал.
#
# Колонки считать не нужно, и это не экономия, а точность: start-of-line плюс
# два cursor-right встают за маркер при любой его ширине (tmux переступает
# ячейку-добивку широкого символа), а end-of-line у tmux и так не берёт
# хвостовые пробелы — длину строки он считает по последнему непробельному.
#
# Проверено 23.09.2026: поиск рамки — на живых экранах 2.1.278 и 2.1.280,
# с текстом и пустых, и на панели zsh; постановка выделения — на панели,
# повторяющей те же байты, потому что живая панель на время проверки
# уходит в copy-mode у того, кто за ней работает.
#
# Чего скрипт не умеет: ввод, не поместившийся в рамку целиком (у длинного
# текста Claude показывает не всё), и режимы, где маркер строки ввода другой, —
# такую панель скрипт не опознаёт и сообщает об этом, ничего не трогая.
set -eu

pane="${1:?нужен pane_id}"

height=$(tmux display-message -p -t "$pane" '#{pane_height}')
rows=$(tmux capture-pane -p -t "$pane" -S 0 -E "$((height - 1))" | awk '
	{ line[NR] = $0 }
	END {
		# Линейка — строка из одних «─». Сравнение побайтовое, но
		# последовательность этого символа в UTF-8 уникальна.
		for (i = NR; i >= 1; i--) {
			t = line[i]
			if (t == "") continue
			gsub(/─/, "", t)
			if (t != "") continue
			if (bottom == 0) { bottom = i; continue }
			top = i
			break
		}
		if (bottom == 0 || top == 0) { print "НЕТ РАМКИ"; exit }
		if (top + 1 > bottom - 1) { print "НЕТ РАМКИ"; exit }

		first = line[top + 1]
		# Маркер «❯» плюс неразрывный пробел U+00A0 — пять байт.
		if (substr(first, 1, 5) != "❯\302\240") { print "НЕ ОПОЗНАНА"; exit }
		if (substr(first, 6) !~ /[^ ]/ && top + 1 == bottom - 1) { print "ПУСТО"; exit }

		# Экранные строки, считая от верха видимой части, с нуля.
		print (top + 1 - 1) " " (bottom - 1 - 1)
	}
')

case "$rows" in
"НЕТ РАМКИ") tmux display-message -t "$pane" "строка ввода Claude Code на экране не найдена"; exit 0 ;;
"НЕ ОПОЗНАНА") tmux display-message -t "$pane" "рамка найдена, маркер строки ввода не опознан"; exit 0 ;;
"ПУСТО") tmux display-message -t "$pane" "строка ввода пуста"; exit 0 ;;
esac

first=${rows% *}
last=${rows#* }

tmux copy-mode -t "$pane"
tmux send-keys -t "$pane" -X history-bottom
tmux send-keys -t "$pane" -X top-line
if [ "$first" -gt 0 ]; then
	tmux send-keys -t "$pane" -X -N "$first" cursor-down
fi
tmux send-keys -t "$pane" -X start-of-line
tmux send-keys -t "$pane" -X -N 2 cursor-right
tmux send-keys -t "$pane" -X begin-selection
if [ "$last" -gt "$first" ]; then
	tmux send-keys -t "$pane" -X -N "$((last - first))" cursor-down
fi
tmux send-keys -t "$pane" -X end-of-line
tmux display-message -t "$pane" "строка ввода выделена: y — копировать, Escape — выйти"
