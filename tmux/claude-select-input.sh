#!/bin/sh
# Выделение текста строки ввода Claude Code (prefix a).
#
# Выделяет САМ Claude Code, а не tmux, и разница видна сразу. Copy-mode tmux
# кладёт поверх панели свой слой и красит выделение своим mode-style (по
# умолчанию жёлтый фон), а Claude в полноэкранном режиме держит собственное
# выделение, красит его как при выделении мышью и по настройке copyOnSelect
# сразу кладёт текст в буфер, отвечая «copied N chars to clipboard». Нужен
# второй вариант, поэтому copy-mode здесь не заводится вовсе: скрипт досылает
# в панель события мыши в формате SGR — нажатие на первом символе ввода,
# протяжка и отпускание у правого края последней строки ввода.
#
# Правый край вместо точной колонки — не упрощение. Хвостовые пробелы Claude
# обрезает сам: проверено 23.09.2026, отпускание в колонке 90 при восьми
# символах текста дало ровно «copied 8 chars to clipboard».
#
# Панель обязана принимать мышь (#{mouse_any_flag}), иначе escape-по-
# следовательности никто не разберёт и они напечатаются прямо в строку ввода.
# Проверка стоит до отправки и молча ничего не делает у панелей без мыши.
#
# Разметка строки ввода, снята с работающей панели 23.09.2026 на 2.1.280:
#
#   ─────────────────────────────  линейка во всю ширину панели
#   ❯<U+00A0>текст                 маркер, НЕРАЗРЫВНЫЙ пробел, текст
#   ─────────────────────────────  линейка
#
# Маркер «❯» встречается и выше по экрану — им же помечены уже отправленные
# сообщения в расшифровке. Поэтому опознаём не по маркеру, а по паре линеек:
# берём нижнюю линейку на экране и ближайшую линейку над ней, между ними и
# лежит ввод, сколько бы строк он ни занимал. Текст начинается в третьей
# колонке: маркер и неразрывный пробел занимают по одной ячейке.
#
# Проверено 23.09.2026 на 2.1.280: поиск рамки — на живых экранах 2.1.278 и
# 2.1.280, с текстом и пустых, и на панели zsh; выделение и «copied N chars» —
# на отдельно запущенной панели Claude Code, потому что живая панель на время
# проверки отдала бы буфер обмена и выделение тому, кто за ней работает.
#
# Чего скрипт не умеет: ввод, не поместившийся в рамку целиком (у длинного
# текста Claude показывает не всё), и режимы, где маркер строки ввода другой, —
# такую панель скрипт не опознаёт и сообщает об этом, ничего не трогая.
# Перенесённый на следующую строку ввод выделяется так же, как выделила бы
# мышь: на месте переноса в буфер попадают перевод строки и два пробела
# отступа вместо одного пробела (110 символов против 108, тот же замер).
set -eu

pane="${1:?нужен pane_id}"

# Мышь панель может и не принимать: /tui default, чужая программа, вышедший
# Claude Code. Тогда последовательности ниже стали бы текстом в строке ввода.
if [ "$(tmux display-message -p -t "$pane" '#{mouse_any_flag}')" != 1 ]; then
	tmux display-message -t "$pane" "панель не принимает мышь, выделять нечем"
	exit 0
fi

height=$(tmux display-message -p -t "$pane" '#{pane_height}')
width=$(tmux display-message -p -t "$pane" '#{pane_width}')
rows=$(tmux capture-pane -p -t "$pane" -S 0 -E "$((height - 1))" | awk '
	{ line[NR] = $0 }
	END {
		# Линейка — строка из одних «─». Сравнение побайтовое, но
		# последовательность этого символа в UTF-8 уникальна.
		for (i = NR; i >= 1; i--) {
			t = line[i]
			if (t == "") continue
			gsub(/─/, "", t)
			if (t != "") continue
			if (bottom == 0) { bottom = i; continue }
			top = i
			break
		}
		if (bottom == 0 || top == 0) { print "НЕТ РАМКИ"; exit }
		if (top + 1 > bottom - 1) { print "НЕТ РАМКИ"; exit }

		first = line[top + 1]
		# Маркер «❯» плюс неразрывный пробел U+00A0 — пять байт.
		if (substr(first, 1, 5) != "❯\302\240") { print "НЕ ОПОЗНАНА"; exit }
		if (substr(first, 6) !~ /[^ ]/ && top + 1 == bottom - 1) { print "ПУСТО"; exit }

		# Строки экрана, считая с единицы: так их нумерует мышь.
		print (top + 1) " " (bottom - 1)
	}
')

case "$rows" in
"НЕТ РАМКИ") tmux display-message -t "$pane" "строка ввода Claude Code на экране не найдена"; exit 0 ;;
"НЕ ОПОЗНАНА") tmux display-message -t "$pane" "рамка найдена, маркер строки ввода не опознан"; exit 0 ;;
"ПУСТО") exit 0 ;;
esac

first=${rows% *}
last=${rows#* }

# SGR: ESC [ < кнопка ; колонка ; строка M — нажатие и протяжка, m —
# отпускание. Протяжка отличается от нажатия битом 32 в номере кнопки.
# Паузы между событиями не нужны: панель читает их одним потоком по порядку.
tmux send-keys -t "$pane" -l "$(printf '\033[<0;3;%dM' "$first")"
tmux send-keys -t "$pane" -l "$(printf '\033[<32;%d;%dM' "$width" "$last")"
tmux send-keys -t "$pane" -l "$(printf '\033[<0;%d;%dm' "$width" "$last")"
